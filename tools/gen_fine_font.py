"""Writes app/fine_font.h: Terminus 12 (third_party/fonts/ter-u12n.bdf, SIL OFL 1.1), ASCII 32..95, for the
screen's fine strip. Each glyph is 12 rows of 6 pixels (bit 5 the left column). Run from the repository root."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
glyphs, enc, rows = {}, None, None
for line in (root / "third_party/fonts/ter-u12n.bdf").read_text().splitlines():
    if line.startswith("ENCODING "): enc = int(line.split()[1])
    elif line == "BITMAP": rows = []
    elif line == "ENDCHAR": glyphs[enc] = rows; rows = None
    elif rows is not None: rows.append(int(line, 16) >> 2)   # 8-bit rows, the 6 pixels in the top bits
out = ["/* Generated by tools/gen_fine_font.py from Terminus 12 (ter-u12n.bdf), Copyright (C) 2020 Dimitar Toshkov",
       " * Zhekov, SIL Open Font License 1.1 (third_party/fonts/Terminus-LICENSE.txt). Do not edit. */",
       "#ifndef FM1_FINE_FONT_H", "#define FM1_FINE_FONT_H", "#include <stdint.h>",
       "enum { FINE_FONT_FIRST = 32, FINE_FONT_LAST = 95, FINE_FONT_W = 6, FINE_FONT_H = 12 };",
       "static const uint8_t fine_font[FINE_FONT_LAST - FINE_FONT_FIRST + 1][FINE_FONT_H] = {"]
for c in range(32, 96):
    r = glyphs[c]; assert len(r) == 12, c
    out.append("    {" + ", ".join(f"0x{v:02x}" for v in r) + f"}},   /* {chr(c)!r} */")
out += ["};", "#endif", ""]
(root / "app/fine_font.h").write_text("\n".join(out))
